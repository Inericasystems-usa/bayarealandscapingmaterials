// LocalBusiness JSON-LD — emitted on every page; richer schema per page below.
const localBusinessJsonLd = {
  "@context": "https://schema.org",
  "@type": "Store", // retail materials yard; Schema.org has no exact "MaterialsYard" type
  "@id": `https://${COMPANY.domain}#business`,
  name: COMPANY.legalName,
  url: `https://${COMPANY.domain}`,
  logo: `https://${COMPANY.domain}/brand/logo-primary.webp`,
  image: `https://${COMPANY.domain}/image/BALM_IMG-14_YARD_CLEAN_191x1.png`,
  telephone: COMPANY.phoneE164,
  email: COMPANY.email,
  address: {
    "@type": "PostalAddress",
    streetAddress: COMPANY.address.street,
    addressLocality: COMPANY.address.city,
    addressRegion: COMPANY.address.state,
    postalCode: COMPANY.address.postalCode,
    addressCountry: COMPANY.address.country,
  },
  geo: { "@type": "GeoCoordinates", latitude: COMPANY.geo.lat, longitude: COMPANY.geo.lng },
  // Only profiles we actually hold a verified URL for (lib/company.ts). Unknown
  // networks stay null there and are filtered out rather than invented.
  sameAs: Object.values(COMPANY.social).filter((u): u is string => Boolean(u)),
  areaServed: { "@type": "GeoCircle", geoMidpoint: { "@type": "GeoCoordinates", latitude: COMPANY.geo.lat, longitude: COMPANY.geo.lng }, geoRadius: `${COMPANY.serviceRadiusMi}mi` },
  // Generated from COMPANY.hoursSpec — the same source the sticky call bar's
  // "Open until 5:00 PM" indicator reads, so schema and UI cannot drift.
  openingHoursSpecification: openingHoursSpecification(),
  // What the yard sells, by catalog category (lib/catalog). Categories only, no
  // offers or prices: the site quotes prices on request.
  hasOfferCatalog: {
    "@type": "OfferCatalog",
    name: "Landscape materials and supplies",
    url: `https://${COMPANY.domain}/products`,
    itemListElement: CATEGORIES.map((c) => ({
      "@type": "OfferCatalog",
      name: c.name,
      url: `https://${COMPANY.domain}${categoryPath(c.slug)}`,
    })),
  },
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html
      lang="en"
      className={`${montserrat.variable} ${openSans.variable} ${jetbrains.variable}`}
      suppressHydrationWarning
    >
      <head>
        {/* Consent Mode v2 defaults, all denied. A plain inline script so it
            runs while the HTML is parsed, before any tag can load. Tag Manager
            itself is mounted by PageShell, on public pages only. */}
        <script
          // eslint-disable-next-line react/no-danger
          dangerouslySetInnerHTML={{ __html: CONSENT_BOOT_SCRIPT }}
        />
        <script
          type="application/ld+json"
          // eslint-disable-next-line react/no-danger
          dangerouslySetInnerHTML={{ __html: JSON.stringify(localBusinessJsonLd).replace(/</g, "\\u003c") }}
        />
      </head>
      <body>
        {children}
        <ServiceWorkerRegister />
      </body>
    </html>
  );
}
