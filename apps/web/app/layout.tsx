import type { Metadata, Viewport } from "next";
import { Montserrat, Open_Sans, JetBrains_Mono } from "next/font/google";
import { ServiceWorkerRegister } from "@/components/ServiceWorkerRegister";
import { COMPANY } from "@/lib/company";
import { CONSENT_BOOT_SCRIPT } from "@/lib/consent";
import { openingHoursSpecification } from "@/lib/hours";
// Next.js processes this global stylesheet at build time.
import "./globals.css";
import React from "react";

// The brand kit's pairing (docs/brand-assets.md): Montserrat for headings, Open
// Sans for body. The design tokens name the families literally ("Montserrat",
// "Open Sans", "JetBrains Mono"), and next/font registers its @font-face under
// those names, so loading them here is what makes the tokens resolve. Before,
// Fraunces was loaded but the tokens asked for Montserrat, which nothing
// loaded: every heading fell back to the system font.
//
// Headings swap in (they carry the brand); body and mono text use `optional`,
// so a slow first visit keeps the metric-matched fallback instead of re-wrapping
// paragraphs mid-read (layout shift); the fonts are cached for the next page.
const montserrat = Montserrat({
  subsets: ["latin"],
  variable: "--font-display",
  display: "swap",
});

const openSans = Open_Sans({
  subsets: ["latin"],
  variable: "--font-sans",
  display: "optional",
  weight: ["400", "500", "600", "700"],
});

const jetbrains = JetBrains_Mono({
  subsets: ["latin"],
  variable: "--font-mono",
  display: "optional",
  weight: ["400", "500"],
  preload: false, // only small labels use it
});

export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#FAFAF9" },
    { media: "(prefers-color-scheme: dark)", color: "#101010" },
  ],
  width: "device-width",
  initialScale: 1,
};

export const metadata: Metadata = {
  metadataBase: new URL(`https://${COMPANY.domain}`),
  title: {
    default: `${COMPANY.legalName} — Bulk Landscape Supply in Richmond, CA`,
    template: `%s · ${COMPANY.shortName}`,
  },
  description: COMPANY.tagline,
  openGraph: {
    type: "website",
    locale: "en_US",
    siteName: COMPANY.shortName,
    title: `${COMPANY.legalName} — Bulk Landscape Supply`,
    description: COMPANY.tagline,
  },
  twitter: { card: "summary_large_image" },
  robots: { index: true, follow: true },
  // The favicon is generated by app/icon.tsx (next.config also serves it at
  // /favicon.ico for clients that ask for that path regardless).
  icons: {
    icon: [{ url: "/icon", type: "image/png", sizes: "32x32" }],
    apple: "/apple-touch-icon.png",
  },
};

// LocalBusiness JSON-LD — emitted on every page; richer schema per page below.
const localBusinessJsonLd = {
  "@context": "https://schema.org",
  "@type": "Store", // retail materials yard; Schema.org has no exact "MaterialsYard" type
  "@id": `https://${COMPANY.domain}#business`,
  name: COMPANY.legalName,
  url: `https://${COMPANY.domain}`,
  telephone: COMPANY.phoneE164,
  email: COMPANY.email,
  address: {
    "@type": "PostalAddress",
    streetAddress: COMPANY.address.street,
    addressLocality: COMPANY.address.city,
    addressRegion: COMPANY.address.state,
    postalCode: COMPANY.address.postalCode,
    addressCountry: COMPANY.address.country,
  },
  geo: { "@type": "GeoCoordinates", latitude: COMPANY.geo.lat, longitude: COMPANY.geo.lng },
  // Only profiles we actually hold a verified URL for (lib/company.ts). Unknown
  // networks stay null there and are filtered out rather than invented.
  sameAs: Object.values(COMPANY.social).filter((u): u is string => Boolean(u)),
  areaServed: { "@type": "GeoCircle", geoMidpoint: { "@type": "GeoCoordinates", latitude: COMPANY.geo.lat, longitude: COMPANY.geo.lng }, geoRadius: `${COMPANY.serviceRadiusMi}mi` },
  // Generated from COMPANY.hoursSpec — the same source the sticky call bar's
  // "Open until 5:00 PM" indicator reads, so schema and UI cannot drift.
  openingHoursSpecification: openingHoursSpecification(),
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html
      lang="en"
      className={`${montserrat.variable} ${openSans.variable} ${jetbrains.variable}`}
      suppressHydrationWarning
    >
      <head>
        {/* Consent Mode v2 defaults, all denied. A plain inline script so it
            runs while the HTML is parsed, before any tag can load. Tag Manager
            itself is mounted by PageShell, on public pages only. */}
        <script
          // eslint-disable-next-line react/no-danger
          dangerouslySetInnerHTML={{ __html: CONSENT_BOOT_SCRIPT }}
        />
        <script
          type="application/ld+json"
          // eslint-disable-next-line react/no-danger
          dangerouslySetInnerHTML={{ __html: JSON.stringify(localBusinessJsonLd).replace(/</g, "\\u003c") }}
        />
      </head>
      <body>
        {children}
        <ServiceWorkerRegister />
      </body>
    </html>
  );
}
